import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import {fileURLToPath} from 'node:url';
import dotenv from 'dotenv';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(projectRoot, '.env');
const outputPath = path.join(projectRoot, 'src', 'config', 'generatedEnvironment.ts');

const fileValues = fs.existsSync(envPath)
  ? dotenv.parse(fs.readFileSync(envPath))
  : {};
const values = {...fileValues, ...process.env};

const supabaseUrl = values.SUPABASE_URL?.trim() ?? '';
const supabasePublishableKey = (
  values.SUPABASE_PUBLISHABLE_KEY
  ?? values.SUPABASE_ANON_KEY
  ?? ''
).trim();
const configured = Boolean(supabaseUrl && supabasePublishableKey);
const enabled = values.SUPABASE_ENABLED === undefined
  ? configured
  : values.SUPABASE_ENABLED.toLowerCase() === 'true';
const studyCondition = values.STUDY_CONDITION?.trim() ?? '';
const pilotBackendHost = values.PILOT_BACKEND_HOST?.trim() ?? '';
const requirePilotBackend = process.argv.includes('--require-pilot-backend');
const supportedStudyConditions = new Set([
  '',
  'StaticPersonalized',
  'RuleBasedAdaptive',
  'ContextualBandit',
]);

if (enabled && !configured) {
  throw new Error(
    'SUPABASE_ENABLED=true requires SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY in .env',
  );
}

if (!supportedStudyConditions.has(studyCondition)) {
  throw new Error(
    'STUDY_CONDITION must be StaticPersonalized, RuleBasedAdaptive, or ContextualBandit',
  );
}

if (pilotBackendHost && (
  !/^[A-Za-z0-9.-]+$/.test(pilotBackendHost)
  || pilotBackendHost.startsWith('.')
  || pilotBackendHost.endsWith('.')
  || pilotBackendHost.includes('..')
)) {
  throw new Error(
    'PILOT_BACKEND_HOST must be a hostname or IPv4 address without a protocol or port',
  );
}

if (requirePilotBackend && !pilotBackendHost) {
  throw new Error(
    'Release builds require PILOT_BACKEND_HOST in .env (for example 192.168.1.25)',
  );
}

if (requirePilotBackend && /^(?:localhost|127(?:\.\d{1,3}){3})$/i.test(pilotBackendHost)) {
  throw new Error(
    'Release builds cannot use a loopback PILOT_BACKEND_HOST because localhost is the phone',
  );
}

const source = `// Generated by scripts/generate-environment.mjs. Do not edit.\n`
  + `export const generatedEnvironment = ${JSON.stringify({
    supabaseEnabled: enabled,
    supabaseUrl,
    supabasePublishableKey,
    studyCondition,
    pilotBackendHost,
  }, null, 2)} as const;\n`;

fs.mkdirSync(path.dirname(outputPath), {recursive: true});
if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== source) {
  fs.writeFileSync(outputPath, source);
}
